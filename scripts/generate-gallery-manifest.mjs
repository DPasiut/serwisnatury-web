// Scans public/images/gallery/<key>/ and generates a static manifest of gallery
// photos consumed by GalleryService. Run automatically before build/serve, or
// continuously via scripts/dev.mjs while `npm start` is running.
import { readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const IMAGE_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg']);

export const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const GALLERY_DIR = join(ROOT, 'public', 'images', 'gallery');
const outFile = join(ROOT, 'src', 'app', 'core', 'gallery-manifest.generated.ts');

function listImages(dir) {
  return readdirSync(dir)
    .filter((name) => IMAGE_EXT.has(name.slice(name.lastIndexOf('.')).toLowerCase()))
    .sort();
}

export function generateGalleryManifest() {
  let categories = [];
  try {
    categories = readdirSync(GALLERY_DIR).filter((name) => statSync(join(GALLERY_DIR, name)).isDirectory());
  } catch {
    categories = [];
  }

  const manifest = {};
  for (const key of categories.sort()) {
    manifest[key] = listImages(join(GALLERY_DIR, key)).map((file) => `images/gallery/${key}/${file}`);
  }

  const content = `// AUTO-GENERATED by scripts/generate-gallery-manifest.mjs — do not edit by hand.
// Regenerated on every build/serve. Add photos under public/images/gallery/<key>/.

export const GALLERY_MANIFEST: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};
`;

  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, content);
  return Object.keys(manifest).length;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const count = generateGalleryManifest();
  console.log(`Gallery manifest written: ${count} categories`);
}
